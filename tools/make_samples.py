r"""検証用のサンプル資料を作るスクリプト（決定論的生成・再実行可能）.

生成物:
  samples/sample_5pages.pdf   … 文字が書かれた5ページのサンプルPDF
  samples/sample_names.xlsx   … A1 に連番モードのベース名、B1:B5 にページ別名（セル別モード用）
  samples\結合入力\           … 結合タブ用のPDF5個（001 / 003 / 008 / 10 / 9。自然順の確認用）
  samples\リネーム入力\       … リネームタブ用のPDF5個（名前がばらばら。自然順の確認用）

実行: py -3 tools\make_samples.py
PDFへの文字の描画は内蔵フォント（Helvetica）のテキスト命令で行うため、
追加ライブラリは使いません（pypdf / openpyxl のみ）。
サンプル資料は毎回作り直す（このスクリプト自身が生成物を作るため）。
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from openpyxl import Workbook  # noqa: E402
from openpyxl.styles import Font  # noqa: E402
from pypdf import PdfWriter  # noqa: E402
from pypdf.generic import DecodedStreamObject, DictionaryObject, NameObject  # noqa: E402

SAMPLE_DIR = ROOT / "samples"
PDF_PATH = SAMPLE_DIR / "sample_5pages.pdf"
XLSX_PATH = SAMPLE_DIR / "sample_names.xlsx"

PAGE_COUNT = 5
# 連番モード（セル値＋連番）で A1 が入るベース名
BASE_NAME = "サンプル統合テスト"
# セル別モード（セル別・連番なし）で B1 から下行きに読むページ別名
PAGE_NAMES = [
    "01_表紙",
    "02_見積内訳",
    "03_納品書",
    "04_請求書",
    "05_検収報告",
]
# ページ本文（Helvetica内蔵フォントのため欧文のみ。ファイル名は日本語を使ってよい）
PAGE_TITLES = [
    "Cover sheet",
    "Estimate breakdown",
    "Delivery note",
    "Invoice",
    "Acceptance report",
]

# --- 結合タブのサンプル（samples\結合入力）--------------------------------
# Explorer の名前順だと 001 → 003 → 008 → 10 → 9 になるが、自然順では 001 → 003 → 008 → 9 → 10。
# ページ数もばらばらにして「N ファイル / M ページ」の検査ができるようにする。
MERGE_DIR = SAMPLE_DIR / "結合入力"
MERGE_SOURCES = [
    ("001.pdf", 2, "Merge source 001"),
    ("003.pdf", 1, "Merge source 003"),
    ("008.pdf", 3, "Merge source 008"),
    ("10.pdf", 1, "Merge source ten"),
    ("9.pdf", 1, "Merge source nine"),
]
# 自然順の期待値（結合順序の検査に使う）
MERGE_NATURAL_ORDER = ["001.pdf", "003.pdf", "008.pdf", "9.pdf", "10.pdf"]
MERGE_PAGES_BY_NAME = {name: pages for name, pages, _title in MERGE_SOURCES}
MERGE_TOTAL_PAGES = sum(pages for _name, pages, _title in MERGE_SOURCES)

# --- リネームタブのサンプル（samples\リネーム入力）------------------------
# 名前がばらばらなPDFを自然順に並べ、Excelの命名ルールを順に割り当てる検査に使う。
RENAME_DIR = SAMPLE_DIR / "リネーム入力"
# (ファイル名, 本文の識別文字列, 本文に書くASCII符号) ※本文はHelveticaのためASCIIのみ
RENAME_SOURCES = [
    ("10_末尾.pdf", "Rename source: last", "last"),
    ("9_中.pdf", "Rename source: middle", "middle"),
    ("008_付録.pdf", "Rename source: appendix", "appendix"),
    ("001_表紙.pdf", "Rename source: cover", "cover"),
    ("003_本文.pdf", "Rename source: body", "body"),
]
# 自然順の期待値（割り当て順序の検査に使う）
RENAME_NATURAL_ORDER = ["001_表紙.pdf", "003_本文.pdf", "008_付録.pdf", "9_中.pdf", "10_末尾.pdf"]


def attach_font(page) -> None:
    """ページに内蔵フォント Helvetica を /F1 として登録する."""
    font = DictionaryObject()
    font[NameObject("/Type")] = NameObject("/Font")
    font[NameObject("/Subtype")] = NameObject("/Type1")
    font[NameObject("/BaseFont")] = NameObject("/Helvetica")
    resources = DictionaryObject()
    resources[NameObject("/Font")] = DictionaryObject({NameObject("/F1"): font})
    page[NameObject("/Resources")] = resources


def write_text_stream(page, lines: list[tuple[int, int, str]]) -> None:
    """ページへ (文字サイズ, y座標, 本文) の行を描画する."""
    body = "BT\n"
    for size, y, text in lines:
        body += f"/F1 {size} Tf 60 {y} Td ({text}) Tj\n"
    body += "ET"
    stream = DecodedStreamObject()
    stream.set_data(body.encode("ascii"))
    page[NameObject("/Contents")] = stream


def draw_page(writer: PdfWriter, index: int) -> None:
    """A4判のページを作り、Helveticaで本文文字を描画する."""
    page = writer.add_blank_page(width=595, height=842)
    attach_font(page)
    write_text_stream(page, [
        (24, 780, "PDF Split Unified - sample document"),
        (16, 745, f"Page {index} of {PAGE_COUNT}"),
        (14, 715, PAGE_TITLES[index - 1]),
        (11, 685, "This page is generated by tools/make_samples.py for verification."),
        (11, 665, f"Corresponding cell B{index} in sample_names.xlsx."),
    ])


def make_pdf() -> None:
    writer = PdfWriter()
    for index in range(1, PAGE_COUNT + 1):
        draw_page(writer, index)
    with PDF_PATH.open("wb") as stream:
        writer.write(stream)


def make_excel() -> None:
    book = Workbook()
    sheet = book.active
    sheet.title = "サンプル"
    sheet["A1"] = BASE_NAME
    for offset, name in enumerate(PAGE_NAMES):
        sheet[f"B{offset + 1}"] = name
    # 読み取り対象セル（A1 / B1:B5）の説明は D 列に置く（検査セルには影響しない）
    bold = Font(bold=True)
    sheet["D1"] = "A1 = 「セル値＋連番」モードのベース名"
    sheet["D2"] = "B1:B5 = 「セル別（連番なし）」モードの開始セル B1 から下行き5ページ分"
    sheet["D3"] = "この列は説明だけで、ファイル名には使いません"
    for cell in ("D1", "D2", "D3"):
        sheet[cell].font = bold
    sheet.column_dimensions["A"].width = 24
    sheet.column_dimensions["B"].width = 24
    sheet.column_dimensions["D"].width = 66
    book.save(XLSX_PATH)
    book.close()


def prepare_sample_dir(folder: Path) -> None:
    """サンプル用のフォルダーを作り直す（再実行しても同じ資料になる）."""
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)


def make_merge_samples() -> list[Path]:
    """結合タブ用のPDFを作る（ページ数の違う5個・名前は自然順にならない順で置く）."""
    prepare_sample_dir(MERGE_DIR)
    made: list[Path] = []
    for name, pages, title in MERGE_SOURCES:
        writer = PdfWriter()
        for page_no in range(1, pages + 1):
            page = writer.add_blank_page(width=595, height=842)
            attach_font(page)
            write_text_stream(page, [
                (20, 780, title),
                (12, 750, f"Page {page_no} of {pages} in {name}"),
                (11, 725, "Generated by tools/make_samples.py for the merge tab."),
            ])
        path = MERGE_DIR / name
        with path.open("wb") as stream:
            writer.write(stream)
        made.append(path)
    return made


def make_rename_samples() -> list[Path]:
    """リネームタブ用のPDFを作る（名前がばらばらな5個・本文に識別文字を入れる）."""
    prepare_sample_dir(RENAME_DIR)
    made: list[Path] = []
    for name, title, code in RENAME_SOURCES:
        writer = PdfWriter()
        page = writer.add_blank_page(width=595, height=842)
        attach_font(page)
        write_text_stream(page, [
            (20, 780, title),
            (12, 750, f"Single page rename sample ({code})"),
            (11, 725, "Generated by tools/make_samples.py for the rename tab."),
        ])
        path = RENAME_DIR / name
        with path.open("wb") as stream:
            writer.write(stream)
        made.append(path)
    return made


def main() -> int:
    SAMPLE_DIR.mkdir(parents=True, exist_ok=True)
    make_pdf()
    make_excel()
    make_merge_samples()
    make_rename_samples()
    print(f"created: {PDF_PATH.relative_to(ROOT)}（{PAGE_COUNT}ページ / {PDF_PATH.stat().st_size:,} バイト）")
    print(f"created: {XLSX_PATH.relative_to(ROOT)}（A1={BASE_NAME} / B1:B5={'、'.join(PAGE_NAMES)}）")
    print(f"created: {MERGE_DIR.relative_to(ROOT)}（{len(MERGE_SOURCES)}ファイル / {MERGE_TOTAL_PAGES}ページ）")
    print(f"created: {RENAME_DIR.relative_to(ROOT)}（{len(RENAME_SOURCES)}ファイル）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
